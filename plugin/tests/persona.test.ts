import { test, expect } from 'claude-code/testing'
import { deskClaudeMd } from '../hooks/persona.ts'

const KPMG = '- If a message looks like KPMG or client work data (client names, engagement details, financials, work documents), reply once that you do not handle KPMG or client information and ask the owner not to send it; never save it to memory.'

test('CLAUDE.md carries the KPMG rule and imports both private files', () => {
  const md = deskClaudeMd()
  expect(md.startsWith('<!-- Generated by the nlk mod')).toBe(true)
  expect(md).toContain('@private/persona.md')
  expect(md).toContain('@private/core.md')
  expect(md.split('\n')).toContain(KPMG)
  for (const banned of ['vault', 'freak', '/ds', 'music', 'Master', 'bot_', 'Approve']) expect(md).not.toContain(banned)
})
