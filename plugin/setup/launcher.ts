import { AWAKE_LABEL, LABEL, SVC_LABEL, TMUX_SESSION, TMUX_SOCKET, appDir, configDir, deskDir, launcherSettingsFile, nlkHome, telegramState } from '../hooks/paths.ts'

const dirOf = (p: string): string => p.slice(0, p.lastIndexOf('/')) || '/'

// launchd's PATH is /usr/bin:/bin:/usr/sbin:/sbin, without bun (the Telegram plugin).
export function launcherPath(a: { home: string; node: string }): string {
  return ['/opt/homebrew/bin', '/usr/local/bin', `${a.home}/.local/bin`, `${a.home}/.bun/bin`, dirOf(a.node), '/usr/bin', '/bin', '/usr/sbin', '/sbin'].join(':')
}

export const resumeMarker = (home: string): string => `${nlkHome(home)}/resume`

// The session's launcher, run as `node run.mjs`. It starts Claude Code in its own tmux server and waits while that lives.
// The resume marker (left by ctl.sh stop, and by this launcher after a first start) makes the next start continue the conversation.
export function runLauncher(a: { home: string; node: string; claude: string; tmux: string }): string {
  const q = JSON.stringify
  const cfg = configDir(a.home)
  const tg = telegramState(a.home)
  const path = launcherPath(a)
  return [
    "import { execFileSync, spawnSync } from 'node:child_process'",
    "import { existsSync, writeFileSync } from 'node:fs'",
    "import { setTimeout as sleep } from 'node:timers/promises'",
    '',
    `const DESK = ${q(deskDir(a.home))}`,
    `const RESUME = ${q(resumeMarker(a.home))}`,
    `const SETTINGS = ${q(launcherSettingsFile(a.home))}`,
    `const TMUX = ${q(a.tmux)}`,
    `const env = { ...process.env, PATH: ${q(path)}, CLAUDE_CONFIG_DIR: ${q(cfg)}, TELEGRAM_STATE_DIR: ${q(tg)}, NLK_HOST: '1' }`,
    `const alive = () => spawnSync(TMUX, ['-L', ${q(TMUX_SOCKET)}, 'has-session', '-t', ${q(TMUX_SESSION)}], { env, stdio: 'ignore' }).status === 0`,
    '',
    'while (!existsSync(DESK)) await sleep(30_000)',
    // The sandbox and permissions live only in that file: without it the assistant does not start.
    "if (!existsSync(SETTINGS)) { console.error('NLK not started: ' + SETTINGS + ' is missing; run ./install.sh again'); process.exit(1) }",
    'const resume = existsSync(RESUME)',
    `if (!alive()) execFileSync(TMUX, ['-L', ${q(TMUX_SOCKET)}, 'new-session', '-d', '-s', ${q(TMUX_SESSION)}, '-e', ${q(`CLAUDE_CONFIG_DIR=${cfg}`)}, '-e', ${q(`TELEGRAM_STATE_DIR=${tg}`)}, '-e', 'NLK_HOST=1', '-e', ${q(`PATH=${path}`)}, ${q(`${a.claude} --settings ${launcherSettingsFile(a.home)} --channels plugin:telegram@claude-plugins-official --model sonnet`)} + (resume ? ' --continue' : '')], { cwd: DESK, env, stdio: 'ignore' })`,
    // After the first start a restart (crash, reboot) carries the conversation on.
    "if (alive()) writeFileSync(RESUME, '')",
    'while (alive()) await sleep(30_000)',
    '',
  ].join('\n')
}

// Each agent's launcher lives in ~/.nlk, so the plists point only there.
export function sessionScript(a: { home: string; node: string }): string {
  return `#!/bin/bash\n# Generated by NLK install.sh.\nexport PATH=${launcherPath(a)}\nexec ${a.node} ${nlkHome(a.home)}/run.mjs\n`
}

export function svcScript(a: { home: string; node: string }): string {
  return [
    '#!/bin/bash',
    '# Generated by NLK install.sh.',
    `export PATH=${[dirOf(a.node), '/usr/bin', '/bin', '/usr/sbin', '/sbin'].join(':')}`,
    `exec ${a.node} ${appDir(a.home)}/server.ts`,
    '',
  ].join('\n')
}

// stop|start|restart for the three agents. `stop` leaves the resume marker, so the next start continues the conversation.
export function ctlScript(a: { home: string; node: string; tmux: string }): string {
  return [
    '#!/bin/bash',
    '# ctl.sh stop|start|restart. Generated by NLK install.sh.',
    `export PATH=${launcherPath(a)}`,
    'uid=$(id -u)',
    `labels=(${LABEL} ${SVC_LABEL} ${AWAKE_LABEL})`,
    'stop() {',
    `  touch ${resumeMarker(a.home)}`,
    '  for l in "${labels[@]}"; do launchctl bootout "gui/$uid/$l" 2>/dev/null; done',
    // bootout can return before launchd lets go of a job; a bootstrap right after then fails.
    '  for l in "${labels[@]}"; do for _ in $(seq 20); do launchctl print "gui/$uid/$l" >/dev/null 2>&1 || break; sleep 0.5; done; done',
    `  ${a.tmux} -L ${TMUX_SOCKET} kill-session -t ${TMUX_SESSION} 2>/dev/null`,
    '  return 0',
    '}',
    'start() {',
    '  for l in "${labels[@]}"; do',
    `    [ -f ${a.home}/Library/LaunchAgents/$l.plist ] || continue`,
    `    launchctl print "gui/$uid/$l" >/dev/null 2>&1 || launchctl bootstrap "gui/$uid" ${a.home}/Library/LaunchAgents/$l.plist || { echo "Could not start $l"; exit 1; }`,
    '  done',
    '}',
    'case ${1:-} in',
    '  stop) stop; echo "NLK stopped" ;;',
    '  start) start; echo "NLK starting" ;;',
    '  restart) stop; start; echo "NLK restarting" ;;',
    '  *) echo "usage: ctl.sh stop|start|restart"; exit 2 ;;',
    'esac',
    '',
  ].join('\n')
}

// Keys sorted and tab-indented as plutil writes them, so a re-run leaves the live plists byte for byte.
export function plist(a: { label: string; args: readonly string[]; keepAlive: boolean; log?: string }): string {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    '<dict>',
  ]
  if (a.keepAlive) lines.push('\t<key>KeepAlive</key>', '\t<true/>')
  lines.push('\t<key>Label</key>', `\t<string>${a.label}</string>`)
  lines.push('\t<key>ProgramArguments</key>', '\t<array>', ...a.args.map(x => `\t\t<string>${x}</string>`), '\t</array>')
  if (a.keepAlive) lines.push('\t<key>RunAtLoad</key>', '\t<true/>')
  if (a.log) lines.push('\t<key>StandardErrorPath</key>', `\t<string>${a.log}</string>`, '\t<key>StandardOutPath</key>', `\t<string>${a.log}</string>`)
  lines.push('</dict>', '</plist>', '')
  return lines.join('\n')
}
